fails = []
for src, keep, gone in CASES:
    out = run(src)
    for frag in [k for k in keep if k]:
        if frag not in out:
            fails.append(("正文被吃掉", src[:40], frag))
    for frag in gone:
        if frag in out:
            fails.append(("残留没砍掉", src[:40], frag))

print(f"{len(CASES)} 个用例，{len(fails)} 个不合格")
for kind, src, frag in fails:
    out = run(src)
    print(f"  [{kind}] {frag!r}\n      IN : {src[:70]}\n      OUT: {out[:70]!r}")
print("\n已知取舍（不作为失败）:")
for src, why in ACCEPTED:
    print(f"  - {src[:34]}… → {why}")
sys.exit(1 if fails else 0)
