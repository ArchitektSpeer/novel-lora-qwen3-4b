#!/usr/bin/env python3
"""第四轮补充：未完待续类改走行内擦除（别再整行杀正文），补上间隔符站点水印与「即可获得观看」共现。"""
from pathlib import Path

R = Path(__file__).resolve().parent


def sub(fname: str, old: str, new: str, count: int = 1) -> None:
    p = R / fname
    text = p.read_text(encoding="utf-8")
    n = text.count(old)
    assert n == count, f"{fname}: 期望 {count} 处 {old[:40]!r}，实际 {n} 处"
    p.write_text(text.replace(old, new), encoding="utf-8")
    print(f"  [OK] {fname}: {old[:44]}…")


# 未完待续/更新更快类基本都粘在正文句尾，交给行内擦除，不再整行删
sub("ad_patterns.txt",
    "\n!(?:未完待续|连载中)[^，。\\n]{0,10}请搜索|(?:最新章节|小说更好)更新更快",
    "")

# 「XX阁/XX网即可获得观看」这类导流句补进共现词表
sub("ad_patterns.txt",
    "!(?:www|http|\\.com|\\.cc|\\.net|小说|阅读|更新|下载|本站|首发|请到|就来|找书|全集)[^，。\\n]{0,16}(?:书客居|文学馆|精华书阁|书海阁|百书屋|零点看书|新笔阁|爱阅|云来阁|爪书屋|飘天文学|无名小说|书香门第)",
    "!(?:www|http|\\.com|\\.cc|\\.net|小说|阅读|更新|下载|本站|首发|请到|就来|找书|全集|一下|获得)[^，。\\n]{0,16}(?:书客居|文学馆|精华书阁|书海阁|百书屋|零点看书|新笔阁|爱阅|云来阁|爪书屋|飘天文学|无名小说|书香门第)")
sub("ad_patterns.txt",
    "!(?:书客居|文学馆|精华书阁|书海阁|百书屋|零点看书|新笔阁|爱阅|云来阁|爪书屋|飘天文学|无名小说|书香门第)[^，。\\n]{0,16}(?:小说网|更新|下载|阅读|本站|首发|最快|最新章节|全集)",
    "!(?:书客居|文学馆|精华书阁|书海阁|百书屋|零点看书|新笔阁|爱阅|云来阁|爪书屋|飘天文学|无名小说|书香门第)[^，。\\n]{0,16}(?:小说网|更新|下载|阅读|本站|首发|最快|最新章节|全集|获得|观看)")

# 间隔符写法的站点名（棉_._.花_._.糖_._._._.網）：合法中文正文不会出现「汉字+多个下划线点」串
